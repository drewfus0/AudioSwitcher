    public class PolicyConfigClient
    {
        private readonly IPolicyConfig? _policyConfig;
        private readonly IPolicyConfigVista? _policyConfigVista;
        private readonly IPolicyConfig10? _policyConfig10;

        public PolicyConfigClient()
        {
            try { _policyConfig = new _PolicyConfigClient() as IPolicyConfig; } catch { }
            if (_policyConfig != null) return;

            try { _policyConfigVista = new _PolicyConfigClient() as IPolicyConfigVista; } catch { }
            if (_policyConfigVista != null) return;

            try { _policyConfig10 = new _PolicyConfigClient() as IPolicyConfig10; } catch { }
        }

        public void SetDefaultEndpoint(string deviceId, ERole role)
        {
            if (_policyConfig != null)
            {
                int hr = _policyConfig.SetDefaultEndpoint(deviceId, role);
                if (hr != 0) Marshal.ThrowExceptionForHR(hr);
                return;
            }
            if (_policyConfigVista != null)
            {
                int hr = _policyConfigVista.SetDefaultEndpoint(deviceId, role);
                if (hr != 0) Marshal.ThrowExceptionForHR(hr);
                return;
            }
            if (_policyConfig10 != null)
            {
                int hr = _policyConfig10.SetDefaultEndpoint(deviceId, role);
                if (hr != 0) Marshal.ThrowExceptionForHR(hr);
                return;
            }
            throw new PlatformNotSupportedException("No supported IPolicyConfig COM interface found on this system.");
        }
    }

